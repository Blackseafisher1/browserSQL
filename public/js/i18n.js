let currentLang = 'en';

export function t(key, ...args) {
  const str = LOCALES[currentLang]?.[key] ?? LOCALES.en[key] ?? key;
  if (!args.length) return str;
  let i = 0;
  return str.replace(/\{(\d+)\}/g, (_, idx) => {
    const n = parseInt(idx, 10);
    return n < args.length ? String(args[n]) : `{${idx}}`;
  });
}

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (!LOCALES[lang]) return;
  currentLang = lang;
  localStorage.setItem('browsersql-lang', lang);
  document.documentElement.lang = lang;
  applyDomTranslations();
  window.dispatchEvent(new CustomEvent('language-changed', { detail: { lang } }));
}

function applyDomTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (el.getAttribute('data-i18n-html') !== null) {
      el.innerHTML = t(key);
    } else {
      el.textContent = t(key);
    }
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
}

export function init() {
  const saved = localStorage.getItem('browsersql-lang');
  if (saved && LOCALES[saved]) {
    currentLang = saved;
  } else {
    currentLang = navigator.language?.startsWith('de') ? 'de' : 'en';
  }
  document.documentElement.lang = currentLang;
  applyDomTranslations();
}
